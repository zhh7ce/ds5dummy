/**
 * @file
 * @brief bridge 内部：麦克风开关报告（0x32）与上行 0x31 麦克风帧的字节布局
 *
 * 开关报告和建链时补发的唤醒报告同为 0x32，但装的是不同子报告：
 * 唤醒那份 [2]=0x90（纯标志块），本文件这两份 [2]=0x91 带一个参数字节——
 * 只有 [4] 的 bit0 是手柄麦克风上行开关。报告整包冻结成两份常量，发哪一份
 * 就把对应数组交给 bt::PostOutput，运行时不拼装、不拷贝。
 *
 * 上行输入报告里麦克风负载的位置也归这里：0x31 的 flags 字节若置了 bit1，
 * 这份报告就不再携带 63 字节状态体，而是一帧从 [3] 起的 71 字节 Opus。
 *
 * @warning 本文件描述的字节都只到"报告体"为止：HIDP 帧头由 bt 后端加，
 *          [1] 的 4-bit seq 与尾部 4 字节 CRC 由 bt::PostOutput 在入队点盖，
 *          两份模板在对应位置保持 0。
 */

#pragma once

