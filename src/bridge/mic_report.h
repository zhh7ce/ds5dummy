/// 0x32 麦克风状态报告体长度。与唤醒报告同为 142 字节是两份报告各自的线
/// 格式事实，不是同一个常量：改其中一份不影响另一份。
inline constexpr size_t kMicStatusReportSize = 142;

/// 参数字节在报告体里的偏移：子报告头 [2]=0x91、长度 [3]=1 之后的数据字节。
inline constexpr size_t kMicParamOffset = 4;

/// 上行 0x31 报告 flags 字节里的麦克风负载标记（bit1）。
inline constexpr uint8_t kMicFlagMask = 0x02;

/// 麦克风 Opus 帧在裸报告体（HIDP 头已剥离）里的起始偏移：report id、
/// flags、以及一个上游固件同样跳过的字节，共 3 字节。
inline constexpr size_t kMicPayloadOffset = 3;

/// 一份带麦克风负载的 0x31 报告体最小长度：偏移 + 一帧 Opus。
inline constexpr size_t kMicReportSize =
    kMicPayloadOffset + core::protocol::kMicOpusSize;

// ---------------------------------------------------------------------------
// 两份冻结模板：关麦 / 开麦
//
// 布局（142 字节，未列出的字节为 0）：
//
// | 偏移      | 值             | 含义 |
// |-----------|----------------|------|
// | 0         | 0x32           | 报告 ID |
// | 1         | 0（传输层覆盖） | 4-bit seq，入队时由 bt::PostOutput 盖 |
// | 2         | 0x91           | 子报告头（0x11 | 1<<7），与唤醒报告的 0x90 不同 |
// | 3         | 1              | 子报告的数据长度：后面只有 1 个参数字节 |
// | 4         | 0b10 / 0b11    | 参数：bit0 = 手柄麦克风上行开关 |
// | 5..137    | 0              | 填充 |
// | 138..141  | 0（传输层覆盖） | 覆盖前 138 字节的 CRC32，入队时由 bt 盖 |
//
// 取值出处是上游 DS5Dongle 的 update_mic_status()（origin/master:src/audio.cpp）：
// 它在主机打开/关闭 UAC 麦克风接口时发这份包，[4] 在 0b11/0b10 之间切换；
// 其余字节从不变化，所以两份形态各冻结一份，不做运行时翻转。
// ---------------------------------------------------------------------------

